#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_tones.py — 合成 esp32s3_macro_cam 设备提示音，生成 main/app_tones.h

规格：16 kHz / 16 bit / 单声道 PCM，小端 int16，内嵌 Flash。
7 种提示音，总时长约 2.75 s，约 88 KB。

v1.7（2026-09-14，需求方选定）：
  - shutter 改用 Canon A1 胶片单反真实录音（CC0，freesound.org/s/579876，
    资产 tools/tones/shutter_canon_a1.wav，裁剪单次"咔-嚓"）；资产缺失时回退合成音。
  - success 改"轻柔双音上行"（880→1175 Hz，两音有间隙 + 长渐弱尾）。
  - fail 改"急促双音下行"（1046→523 Hz 大跳，首音短+间隙短+末音干脆；需求方明确不要三连音）。
"""
import math
import os
import struct
import wave

SR = 16000            # 采样率 16 kHz
OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "main", "app_tones.h")
SHUTTER_WAV = os.path.join(os.path.dirname(__file__), "tones", "shutter_canon_a1.wav")


def load_wav_mono16k(path):
    """读取 16 kHz / 16 bit / 单声道 WAV，返回 float 样本列表 [-1, 1]"""
    with wave.open(path, "rb") as w:
        assert w.getframerate() == SR, "快门音资产采样率必须为 16 kHz"
        assert w.getnchannels() == 1 and w.getsampwidth() == 2, "必须为 16 bit 单声道"
        raw = w.readframes(w.getnframes())
    n = len(raw) // 2
    return [struct.unpack_from("<h", raw, i * 2)[0] / 32768.0 for i in range(n)]


def _ramp(samples, attack, release):
    """对采样序列做首尾淡入淡出，避免爆音"""
    out = []
    n = len(samples)
    a = max(1, int(attack * SR))
    r = max(1, int(release * SR))
    for i, s in enumerate(samples):
        env = 1.0
        if i < a:
            env = i / a
        if i >= n - r:
            env = min(env, (n - 1 - i) / r)
        out.append(s * env)
    return out


def sine(freq, dur, amp=0.85, decay=0.0, attack=0.005, release=0.005):
    """单个正弦段。decay>0 时指数衰减（decay 为时间常数秒）"""
    n = int(dur * SR)
    seg = []
    for i in range(n):
        t = i / SR
        env = math.exp(-t / decay) if decay > 0 else 1.0
        seg.append(amp * env * math.sin(2 * math.pi * freq * t))
    return _ramp(seg, attack, release)


def silence(dur):
    return [0.0] * int(dur * SR)


def tone(segments):
    """把多段拼接成 int16 样本列表"""
    data = []
    for seg in segments:
        data.extend(seg)
    # 归一化到 int16
    peak = max(1.0, max(abs(x) for x in data))
    return [int(round(x / peak * 32767)) for x in data]


def build():
    tones = {}
    # 1. 唤醒/开机：上行「叮」0.25s，880Hz 持续
    tones["wakeup"] = tone([sine(880, 0.25, amp=0.85, attack=0.008, release=0.025)])

    # 2. 快门：Canon A1 真实录音（CC0）裁剪单次「咔-嚓」~205 ms（需求方选定，v1.7）
    #    资产缺失时回退为合成短促 click（勿用强衰减——阶段 5 教训）
    if os.path.exists(SHUTTER_WAV):
        tones["shutter"] = tone([load_wav_mono16k(SHUTTER_WAV)])
    else:
        tones["shutter"] = tone([sine(1800, 0.10, amp=0.7)])

    # 3. 成功：轻柔双音上行「叮…咚♪」~490 ms（需求方选定，v1.7）
    #    两音之间留 90 ms 间隙（修复旧版"叮咚挤成一团"），尾部 100/120 ms 渐弱 = 轻柔感
    tones["success"] = tone([
        sine(880, 0.18, amp=0.80, attack=0.008, release=0.100),
        silence(0.090),
        sine(1175, 0.22, amp=0.80, attack=0.008, release=0.120),
    ])

    # 4. 失败：急促双音下行「嘀-嘟」~320 ms（需求方选定，v1.7；明确不要三连音）
    #    大跳下行（两个八度）= 错误/拒绝感；首音短 + 间隙短 + 末音干脆 = 急促感
    tones["fail"] = tone([
        sine(1046, 0.10, amp=0.85, attack=0.005, release=0.025),
        silence(0.060),
        sine(523, 0.16, amp=0.85, attack=0.005, release=0.040),
    ])

    # 5. 卡缺失/容量不足：三短「哔哔哔」0.6s，1400Hz x3
    tones["sd_error"] = tone([
        sine(1400, 0.13, amp=0.85, attack=0.006, release=0.015),
        silence(0.07),
        sine(1400, 0.13, amp=0.85, attack=0.006, release=0.015),
        silence(0.07),
        sine(1400, 0.13, amp=0.85, attack=0.006, release=0.015),
    ])

    # 6. 低电量：低频两声「咚」0.5s，500Hz x2（原 150Hz 小喇叭放不出，抬高到 500Hz）
    tones["low_battery"] = tone([
        sine(500, 0.20, amp=0.9, attack=0.008, release=0.03),
        silence(0.06),
        sine(500, 0.20, amp=0.9, attack=0.008, release=0.03),
    ])

    # 7. 即将休眠（入睡前 10 s 预警）：880Hz -> 660Hz 双音下行，与「叮咚」的上行形成对比
    tones["sleep_warn"] = tone([
        sine(880, 0.12, amp=0.85, attack=0.006, release=0.015),
        silence(0.08),
        sine(660, 0.12, amp=0.85, attack=0.006, release=0.015),
    ])

    return tones


def to_c_bytes(samples):
    """int16 样本 -> 小端字节串，按每行 16 字节输出 C 数组文本"""
    raw = bytearray()
    for s in samples:
        raw += (s & 0xFFFF).to_bytes(2, "little")
    lines = []
    for i in range(0, len(raw), 16):
        chunk = raw[i:i + 16]
        lines.append("    " + ",".join("0x%02X" % b for b in chunk) + ",")
    return "\n".join(lines), len(raw)


def main():
    tones = build()
    order = ["wakeup", "shutter", "success", "fail", "sd_error", "low_battery", "sleep_warn"]
    id_names = {
        "wakeup": "TONE_WAKEUP", "shutter": "TONE_SHUTTER", "success": "TONE_SUCCESS",
        "fail": "TONE_FAIL", "sd_error": "TONE_SD_ERROR", "low_battery": "TONE_LOW_BATTERY",
        "sleep_warn": "TONE_SLEEP_WARN",
    }

    parts = []
    parts.append("/* Auto-generated by tools/gen_tones.py -- DO NOT EDIT */")
    parts.append("/* 16 kHz / 16 bit / mono PCM, little-endian int16, embedded in flash (design doc 4.9) */")
    parts.append("#pragma once")
    parts.append("#include <stdint.h>")
    parts.append("")
    parts.append("#define TONE_SAMPLE_RATE 16000")
    parts.append("")

    total = 0
    for name in order:
        samples = tones[name]
        body, nbytes = to_c_bytes(samples)
        total += nbytes
        parts.append("static const uint8_t tone_%s_pcm[] = {" % name)
        parts.append(body)
        parts.append("};")
        parts.append("")
        parts.append("#define TONE_%s_BYTES (%u)" % (name.upper(), nbytes))
        parts.append("#define TONE_%s_MS   (%u)" % (name.upper(), round(len(samples) * 1000 / SR)))
        parts.append("")

    # 汇总表：按 tone_id_t 顺序索引
    parts.append("typedef struct {")
    parts.append("    const uint8_t *pcm;   /* PCM data (flash resident) */")
    parts.append("    uint32_t      bytes;  /* length in bytes */")
    parts.append("    uint32_t      ms;     /* duration in ms */")
    parts.append("} tone_entry_t;")
    parts.append("")
    parts.append("static const tone_entry_t g_tone_table[] = {")
    for name in order:
        parts.append("    { tone_%s_pcm, TONE_%s_BYTES, TONE_%s_MS }," %
                     (name, name.upper(), name.upper()))
    parts.append("};")
    parts.append("")

    header = "\n".join(parts)
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
    print("WROTE %s" % OUT_PATH)
    print("TOTAL %d bytes (%.1f KB)" % (total, total / 1024.0))
    for name in order:
        print("  %-12s %5d samples  %4d ms  %5d bytes" %
              (name, len(tones[name]), round(len(tones[name]) * 1000 / SR), 0))


if __name__ == "__main__":
    main()
